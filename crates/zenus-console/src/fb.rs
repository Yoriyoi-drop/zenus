use core::sync::atomic::{AtomicBool, AtomicUsize, Ordering};

pub struct Framebuffer {
    pub addr: u64,
    pub width: u64,
    pub height: u64,
    pub bpp: u16,
    pub pitch: u16,
}

static FB: core::sync::atomic::AtomicU64 = core::sync::atomic::AtomicU64::new(0);
static FB_WIDTH: core::sync::atomic::AtomicU64 = core::sync::atomic::AtomicU64::new(0);
static FB_HEIGHT: core::sync::atomic::AtomicU64 = core::sync::atomic::AtomicU64::new(0);
static FB_BPP: core::sync::atomic::AtomicU16 = core::sync::atomic::AtomicU16::new(0);
static FB_PITCH: core::sync::atomic::AtomicU16 = core::sync::atomic::AtomicU16::new(0);
static FB_INIT: AtomicBool = AtomicBool::new(false);
static CURSOR_X: AtomicUsize = AtomicUsize::new(0);
static CURSOR_Y: AtomicUsize = AtomicUsize::new(0);

const CHAR_WIDTH: u64 = 8;
const CHAR_HEIGHT: u64 = 16;

pub fn init(fb: &Framebuffer) {
    FB.store(fb.addr, Ordering::Release);
    FB_WIDTH.store(fb.width, Ordering::Relaxed);
    FB_HEIGHT.store(fb.height, Ordering::Relaxed);
    FB_BPP.store(fb.bpp, Ordering::Relaxed);
    FB_PITCH.store(fb.pitch, Ordering::Relaxed);
    FB_INIT.store(true, Ordering::Release);
    CURSOR_X.store(0, Ordering::Relaxed);
    CURSOR_Y.store(0, Ordering::Relaxed);
    clear();
}

pub fn is_initialized() -> bool {
    FB_INIT.load(Ordering::Acquire)
}

pub fn clear() {
    if !FB_INIT.load(Ordering::Acquire) {
        return;
    }
    let addr = FB.load(Ordering::Acquire);
    let height = FB_HEIGHT.load(Ordering::Relaxed) as usize;
    let pitch = FB_PITCH.load(Ordering::Relaxed) as usize;
    let row_bytes = pitch;
    for y in 0..height {
        let row = row_bytes * y;
        for x in 0..(pitch as usize) {
            unsafe {
                core::ptr::write_volatile((addr as *mut u8).add(row + x), 0u8);
            }
        }
    }
    CURSOR_X.store(0, Ordering::Relaxed);
    CURSOR_Y.store(0, Ordering::Relaxed);
}

fn put_pixel(x: u64, y: u64, r: u8, g: u8, b: u8) {
    if !FB_INIT.load(Ordering::Acquire) {
        return;
    }
    let addr = FB.load(Ordering::Acquire);
    let width = FB_WIDTH.load(Ordering::Relaxed);
    let height = FB_HEIGHT.load(Ordering::Relaxed);
    let pitch = FB_PITCH.load(Ordering::Relaxed) as u64;
    let bpp = FB_BPP.load(Ordering::Relaxed);

    if x >= width || y >= height {
        return;
    }

    let offset = y * pitch + x * (bpp as u64 / 8);
    unsafe {
        let ptr = (addr + offset) as *mut u8;
        core::ptr::write_volatile(ptr, b);
        core::ptr::write_volatile(ptr.add(1), g);
        core::ptr::write_volatile(ptr.add(2), r);
        if bpp >= 32 {
            core::ptr::write_volatile(ptr.add(3), 0u8);
        }
    }
}

fn draw_char_glyph(
    c: u8,
    x: u64,
    y: u64,
    fg_r: u8,
    fg_g: u8,
    fg_b: u8,
    bg_r: u8,
    bg_g: u8,
    bg_b: u8,
) {
    let glyph = match c {
        0x20..=0x7E => FONT_DATA[(c - 0x20) as usize],
        _ => return,
    };
    for row in 0..16 {
        let bits = glyph[row];
        for col in 0..8 {
            if (bits >> (7 - col)) & 1 != 0 {
                put_pixel(x + col as u64, y + row as u64, fg_r, fg_g, fg_b);
            } else {
                put_pixel(x + col as u64, y + row as u64, bg_r, bg_g, bg_b);
            }
        }
    }
}

fn scroll() {
    if !FB_INIT.load(Ordering::Acquire) {
        return;
    }
    let addr = FB.load(Ordering::Acquire);
    let height = FB_HEIGHT.load(Ordering::Relaxed);
    let pitch = FB_PITCH.load(Ordering::Relaxed) as u64;
    let char_height = CHAR_HEIGHT;
    let row_bytes = pitch;
    let scroll_bytes = char_height * row_bytes;
    let total_rows = height * row_bytes;
    unsafe {
        core::ptr::copy(
            (addr + scroll_bytes) as *const u8,
            addr as *mut u8,
            (total_rows - scroll_bytes) as usize,
        );
        core::ptr::write_bytes(
            (addr + total_rows - scroll_bytes) as *mut u8,
            0,
            scroll_bytes as usize,
        );
    }
    let cy = CURSOR_Y.load(Ordering::Relaxed);
    if cy > 0 {
        CURSOR_Y.store(cy - 1, Ordering::Relaxed);
    }
}

pub fn write_str(s: &str) {
    if !FB_INIT.load(Ordering::Acquire) {
        return;
    }
    let width = FB_WIDTH.load(Ordering::Relaxed);
    let height = FB_HEIGHT.load(Ordering::Relaxed);
    let cols = (width / CHAR_WIDTH) as usize;
    let rows = (height / CHAR_HEIGHT) as usize;

    let mut in_escape = false;
    let mut ansi_buf = [0u8; 16];
    let mut ansi_len = 0usize;

    for byte in s.bytes() {
        if byte == 0x1B {
            in_escape = true;
            ansi_len = 0;
            continue;
        }

        if in_escape {
            if ansi_len < ansi_buf.len() {
                ansi_buf[ansi_len] = byte;
                ansi_len += 1;
            }
            if byte >= 0x40 && byte <= 0x7E {
                in_escape = false;
                if ansi_len >= 2 && ansi_buf[0] == b'[' {
                    if ansi_len == 2 && ansi_buf[1] == b'H' {
                        CURSOR_X.store(0, Ordering::Relaxed);
                        CURSOR_Y.store(0, Ordering::Relaxed);
                    } else if ansi_len >= 3 {
                        let cmd = ansi_buf[ansi_len - 1];
                        if cmd == b'J' && ansi_len == 3 && ansi_buf[1] == b'2' {
                            clear();
                        }
                    }
                }
            }
            continue;
        }

        match byte {
            b'\n' => {
                CURSOR_X.store(0, Ordering::Relaxed);
                CURSOR_Y.fetch_add(1, Ordering::Relaxed);
            }
            b'\r' => {
                CURSOR_X.store(0, Ordering::Relaxed);
            }
            b'\t' => {
                let tab = 4;
                let base_y = CURSOR_Y.load(Ordering::Relaxed) * CHAR_HEIGHT as usize;
                loop {
                    let cx = CURSOR_X.load(Ordering::Relaxed);
                    if cx >= cols || CURSOR_X.load(Ordering::Relaxed) % tab == 0 {
                        break;
                    }
                    let base_x = cx * CHAR_WIDTH as usize;
                    draw_char_glyph(
                        b' ',
                        base_x as u64,
                        base_y as u64,
                        0xAA,
                        0xAA,
                        0xAA,
                        0,
                        0,
                        0,
                    );
                    CURSOR_X.fetch_add(1, Ordering::Relaxed);
                }
            }
            0x20..=0x7E => {
                let cx = CURSOR_X.load(Ordering::Relaxed);
                let cy = CURSOR_Y.load(Ordering::Relaxed);
                if cx < cols {
                    let base_x = cx * CHAR_WIDTH as usize;
                    let base_y = cy * CHAR_HEIGHT as usize;
                    draw_char_glyph(
                        byte,
                        base_x as u64,
                        base_y as u64,
                        0xAA,
                        0xAA,
                        0xAA,
                        0,
                        0,
                        0,
                    );
                    CURSOR_X.fetch_add(1, Ordering::Relaxed);
                }
            }
            _ => {}
        }
        let cx = CURSOR_X.load(Ordering::Relaxed);
        if cx >= cols {
            CURSOR_X.store(0, Ordering::Relaxed);
            CURSOR_Y.fetch_add(1, Ordering::Relaxed);
        }
        let mut cy = CURSOR_Y.load(Ordering::Relaxed);
        while cy >= rows {
            scroll();
            cy = CURSOR_Y.load(Ordering::Relaxed);
        }
    }
}

